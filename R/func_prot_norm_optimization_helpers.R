# getRuvIIIReplicateMatrixHelper
# ----------------------------------------------------------------------------
## -----------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
#'Converts a design matrix to a biological replicate matrix for use with ruvIII.
#'@param design_matrix The design matrix with the sample ID in one column and the experimental group in another column
#'@param sample_id_column The name of the column with the sample ID, tidyverse style input.
#'@param grouping_variable The name of the column with the experimental group, tidyverse style input.
#'@param temp_column The name of the temporary column that indicates which samples are biological replicates of the same experimental group.
#'@return A numeric matrix with rows as samples, columns as experimental group, and a value of 1 for samples within the same experimental group represented by the same column, and a value of zero otherwise.
#'@export
getRuvIIIReplicateMatrixHelper <- function(design_matrix, sample_id_column, grouping_variable, temp_column = is_replicate_temp) {

  ruvIII_replicates_matrix <- design_matrix |>
    dplyr::select({ { sample_id_column } }, { { grouping_variable } }) |>
    mutate({ { temp_column } } := 1) |>
    pivot_wider(id_cols = as_string( as_name(enquo(sample_id_column ))),
                names_from = { { grouping_variable } },
                values_from = { { temp_column } },
                values_fill = 0) |>
    column_to_rownames(as_string(as_name(enquo(sample_id_column)))) |>
    as.matrix()

  ruvIII_replicates_matrix
}

#' Choose the RUV-III replicate structure from the design (user decision 2026-10-09).
#' Technical replicates (samples sharing group and replicate number) are the replicate set when
#' the design has any; otherwise every sample of the RUV grouping variable is a replicate.
#' @param design_matrix Design table.
#' @param sample_id,group_id,technical_replicate_id Column names from the S4 slots.
#' @param ruv_grouping_variable Fallback grouping column.
#' @return `design` with a `.ruv_replicate_block` column, `structure` (`technical_replicates` or
#'   `group`) and `blocks` (number of replicate sets).
#' @noRd
#' Which proteins are observed (finite) in every design sample: the controls RUV-III can use for every
#' sample, and therefore the upper bound on the number of factors it can estimate.
#' @return Logical vector, one entry per row of the protein table.
#' @noRd
ruvCompleteControlRows <- function(theObject) {
  samples <- as.character(theObject@design_matrix[[theObject@sample_id]])
  samples <- intersect(samples, names(theObject@protein_quant_table))
  values <- as.matrix(theObject@protein_quant_table[, samples, drop = FALSE])
  rowSums(!is.finite(values)) == 0L
}

#' The refusal of an RUV percentage sweep that found no valid percentage (KIT-101 F-27)
#'
#' When percentages were skipped because their elbow k exceeded the controls observed in every sample
#' (KIT-005), the refusal names that cause and what the user can do; otherwise it is `NULL` and the caller
#' keeps its existing refusal. Message only: the sweep's decision is unchanged.
#' @param percentages,status,best_k Per tested percentage, from the sweep's trace.
#' @param complete_controls Per tested percentage, the controls observed in every sample (NA where not counted).
#' @param feature_label Plural feature noun, e.g. `"proteins"`.
#' @return A single string, or `NULL` when no percentage was skipped for that cause.
#' @noRd
ruvNoValidPercentageMessage <- function(percentages, status, best_k, complete_controls, feature_label) {
  skipped <- status %in% "skipped_k_exceeds_complete_controls"
  if (!any(skipped)) {
    return(NULL)
  }
  spanText <- \(x) {
    x <- range(x, na.rm = TRUE)
    if (x[[1L]] == x[[2L]]) format(x[[1L]]) else paste0(x[[1L]], "-", x[[2L]])
  }
  tried <- if (all(skipped)) {
    "at every control percentage tried"
  } else {
    sprintf("at %d of the %d control percentages tried", sum(skipped), length(skipped))
  }
  sprintf(paste0("No valid percentage found: RUV-III needs control %s observed in every sample; %s (%s%%), ",
    "only %s were (k = %s). Filter for completeness first, lower k, or run normalisation without RUV."),
    feature_label, tried, spanText(percentages[skipped]), spanText(complete_controls[skipped]),
    spanText(best_k[skipped]))
}

#' The technical replicate block of a design, from the object's one declaration (KIT-035)
#'
#' The protein object declares its technical replicate column once (`technical_replicate_id`, set by the design
#' step to `tech_rep_group`); the DA model's block and RUV-III's replicate structure both come from it. The block
#' is the declared column's value, prefixed by the group where a value recurs across groups (a plain replicate
#' index), so blocks are nested in groups and the string equals the `group_replicates` block the DA model used
#' before. A design carries technical replicates only when the block has duplicates and is not spanned by the
#' design's group: a block that equals its group within every group level is already encoded by the design
#' matrix, limma would set the intrablock correlation to zero, and RUV-III's replicate matrix would equal the
#' group's, so such a design is standard, with the reason recorded.
#' @param design_matrix Ordered sample metadata.
#' @param group_id,technical_replicate_id Column names from the object's slots.
#' @return List `block` (character per row, or NULL), `technical` (logical), `reason` (one of
#'   `technical_replicates`, `spanned_by_design`, `no_duplicates`, `no_declaration`, `missing_values`), `blocks`.
#' @noRd
resolveProtTechnicalReplicateBlock <- function(design_matrix, group_id, technical_replicate_id) {
  stopifnot(is.data.frame(design_matrix))
  declared <- is.character(technical_replicate_id) && length(technical_replicate_id) == 1L &&
    is.character(group_id) && length(group_id) == 1L &&
    all(c(group_id, technical_replicate_id) %in% names(design_matrix))
  if (!declared) return(list(block = NULL, technical = FALSE, reason = "no_declaration", blocks = 0L))
  group <- as.character(design_matrix[[group_id]])
  value <- design_matrix[[technical_replicate_id]]
  if (anyNA(value)) return(list(block = NULL, technical = FALSE, reason = "missing_values", blocks = 0L))
  value <- as.character(value)
  nested <- all(vapply(split(group, value), function(g) length(unique(g)) == 1L, logical(1)))
  block <- if (nested) value else paste(group, value, sep = "_")
  if (!anyDuplicated(block)) return(list(block = block, technical = FALSE, reason = "no_duplicates", blocks = length(block)))
  spanned <- all(vapply(split(block, group), function(b) length(unique(b)) == 1L, logical(1)))
  list(block = block, technical = !spanned, reason = if (spanned) "spanned_by_design" else "technical_replicates",
    blocks = length(unique(block)))
}

#' Refuse a differential analysis without biological replication (KIT-128 K128-1, the user's rule of 2026-11-17, every
#' omic): a design whose every group is one biological unit measured more than once (the rule's `spanned_by_design`)
#' has no biological replicate to test against, and its technical replicates are not independent samples.
#' @param replicate `resolveProtTechnicalReplicateBlock`'s result.
#' @param groups The group of each row the rule read.
#' @return `replicate`, invisibly; otherwise an error of class `omics_da_no_biological_replication` naming the groups.
#' @noRd
refuseNoBiologicalReplication <- function(replicate, groups) {
  if (!identical(replicate$reason, "spanned_by_design")) return(invisible(replicate))
  rlang::abort(sprintf(paste("no biological replication: every group is one biological unit measured more than once",
    "(groups %s), so there is no biological replicate to test against. Each group needs at least two biological units."),
    paste(unique(as.character(groups)), collapse = ", ")), class = "omics_da_no_biological_replication")
}

resolveProtRuvReplicateBlocks <- function(design_matrix, sample_id, group_id, technical_replicate_id,
                                          ruv_grouping_variable) {
  stopifnot(is.data.frame(design_matrix), sample_id %in% names(design_matrix))
  # KIT-035: the same declaration and rule as the DA model (`resolveProtTechnicalReplicateBlock`).
  replicate <- resolveProtTechnicalReplicateBlock(design_matrix, group_id, technical_replicate_id)
  if (isTRUE(replicate$technical)) {
    design_matrix$.ruv_replicate_block <- replicate$block
    structure <- "technical_replicates"
  } else {
    if (!ruv_grouping_variable %in% names(design_matrix)) {
      stop(sprintf("RUV grouping variable `%s` is absent from the design matrix", ruv_grouping_variable), call. = FALSE)
    }
    design_matrix$.ruv_replicate_block <- as.character(design_matrix[[ruv_grouping_variable]])
    structure <- "group"
  }
  list(design = design_matrix, structure = structure, blocks = length(unique(design_matrix$.ruv_replicate_block)))
}

# ----------------------------------------------------------------------------
# getNegCtrlProtAnovaHelper
# ----------------------------------------------------------------------------
#' Identify negative control proteins for use in removal of unwanted variation, using an ANOVA test.
#' @param data_matrix A matrix containing the log (base 2) protein abundance values where each column represents a sample and each row represents a protein group, and proteins as rows. The row ID are the protein accessions. The data is preferably median-scaled with missing values imputed.
#' @param design_matrix A data frame with the design matrix. Matches sample IDs to group IDs.
#' @param grouping_variable The name of the column with the experimental group, as a string.
#' @param num_neg_ctrl The number of negative control genes to select. Typically the number of genes with the highest q-value (e.g. least statistically significant). Default is 100
#' @param ruv_qval_cutoff The FDR threshold. No proteins with q-values lower than this value are included in the list of negative control proteins. This means the number of negative control proteins could be less than the number specified in \code{num_neg_ctrl} when some were excluded by this threshold.
#' @param ruv_fdr_method The FDR calculation method, default is "qvalue". The other option is "BH"
#' @param exclude_pool_samples Logical. If TRUE (default), automatically exclude samples from groups containing "Pool" in their name from ANOVA calculation. Pool/QC samples are excluded from negative control selection but remain in RUV-III correction.
#' @param candidate_rule \code{"q_table_order"} (the default; every caller but the lipidomics and metabolomics methods): candidates ranked by q-value, highest first, ties in the order of \code{data_matrix}'s rows. \code{"p_id_two_groups"} (KIT-190, the lipidomics and metabolomics methods): features observed in fewer than two groups are not candidates (they stay in the BH family with p = 1), and candidates are ranked by p-value, highest first, ties broken by row name in C-locale byte order.
#' @details Features are ranked as \code{candidate_rule} says; a feature observed in fewer than two groups scores p = 1. A \code{design_matrix} without the \code{grouping_variable} column, or fewer than two groups left after leaving out the pools, is an error of class \code{multischolar_ruv_grouping_unusable}.
#' @return A boolean vector which indicates which row in the input data matrix is a control gene. The row is included if the value is TRUE. The names of each element is the row ID / protein accessions of the input data matrix.
#'@export
#' @param percentage_as_neg_ctrl Runtime inputs used by this function; see the usage section for accepted values.
getNegCtrlProtAnovaHelper <- function(data_matrix
                                , design_matrix
                                , grouping_variable = "group"
                                , percentage_as_neg_ctrl = 10
                                , num_neg_ctrl = round( nrow(data_matrix)*percentage_as_neg_ctrl/100, 0)
                                , ruv_qval_cutoff = 0.05
                                , ruv_fdr_method = "qvalue"
                                , exclude_pool_samples = TRUE
                                , candidate_rule = c("q_table_order", "p_id_two_groups")) {

  candidate_rule <- match.arg(candidate_rule)

  # Without its grouping column the ANOVA has nothing to compare and every feature would score p = 1, so the
  # first rows would be taken (KIT-190). Refused, except under the earlier rule kept for replaying old records.
  if (!identical(getOption("MultiScholaR.ruv_control_grouping", "kept"), "dropped") &&
      !grouping_variable %in% colnames(design_matrix)) {
    cli::cli_abort(
      "Control features cannot be chosen: the design passed to the control selection has no column '{grouping_variable}', so the features cannot be compared between groups. Pass a design that holds the grouping column, with sample ids as row names.",
      class = c("multischolar_ruv_grouping_unusable", "multischolar_refusal")
    )
  }

  ## Both percentage_as_neg_ctrl and num_neg_ctrl is missing, and number of proteins >= 50 use only 10 percent of the proteins as negative control by default
  if((is.null(percentage_as_neg_ctrl) ||
     is.na(percentage_as_neg_ctrl) ) &&
     (is.null(num_neg_ctrl) ||
      is.na(num_neg_ctrl) ) &&
     nrow(data_matrix) >= 50 ) {
    num_neg_ctrl <- round( nrow(data_matrix)*10/100, 0)
    warning(
      getFunctionName(),
      ": Using 10% of proteins from the input matrix as negative controls by default."
    )
  } else if (!is.null(percentage_as_neg_ctrl) &
             !is.na(percentage_as_neg_ctrl)) {
    num_neg_ctrl <- round( nrow(data_matrix)*percentage_as_neg_ctrl/100, 0)
  } else if(!is.null(num_neg_ctrl) &
       !is.na(num_neg_ctrl)) {
    num_neg_ctrl <- as.integer(num_neg_ctrl)
  } else {
    stop(paste0( getFunctionName(), ": Please provide either percentage_as_neg_ctrl or num_neg_ctrl.\n"))
  }
  

  # --- Pool/QC Sample Handling ---
  # Pool/QC samples should not influence negative control selection but can help
  # estimate unwanted variation patterns in RUV-III correction
  data_matrix_for_anova <- data_matrix
  design_matrix_for_anova <- design_matrix
  
  if (exclude_pool_samples) {
    # Detect Pool/QC groups (case-insensitive detection)
    all_groups <- unique(design_matrix[[grouping_variable]])
    is_pool_group <- grepl("pool", all_groups, ignore.case = TRUE)
    pool_group_names <- all_groups[is_pool_group]
    
    if (length(pool_group_names) > 0) {
      # Identify samples that belong to Pool groups
      samples_in_design <- rownames(design_matrix)
      pool_samples <- samples_in_design[design_matrix[[grouping_variable]] %in% pool_group_names]
      
      # Filter to samples present in both design matrix and data matrix columns
      pool_samples_in_data <- intersect(pool_samples, colnames(data_matrix))
      
      if (length(pool_samples_in_data) > 0) {
        # Log Pool/QC exclusion details
        message(sprintf("*** NEG CTRL ANOVA: Detected %d Pool/QC group(s): %s ***", 
                       length(pool_group_names), paste(pool_group_names, collapse = ", ")))
        message(sprintf("*** NEG CTRL ANOVA: Excluding %d Pool samples from ANOVA ***", 
                       length(pool_samples_in_data)))
        
        # Create filtered matrices excluding Pool samples
        non_pool_samples <- setdiff(colnames(data_matrix), pool_samples_in_data)
        data_matrix_for_anova <- data_matrix[, non_pool_samples, drop = FALSE]
        design_matrix_for_anova <- design_matrix[non_pool_samples, , drop = FALSE]
        
        message(sprintf("*** NEG CTRL ANOVA: Using %d non-Pool samples for negative control selection ***", 
                       ncol(data_matrix_for_anova)))
        
        # Validate sufficient samples remain for ANOVA
        remaining_groups <- unique(design_matrix_for_anova[[grouping_variable]])
        if (length(remaining_groups) < 2) {
          stop(errorCondition(paste("*** NEG CTRL ANOVA ERROR: After excluding Pool samples, only", 
                    length(remaining_groups), 
                    "group(s) remain. Need at least 2 groups for ANOVA. ***"),
                    class = "multischolar_ruv_grouping_unusable", call = sys.call()))
        }
        
        # Check samples per group
        samples_per_group <- table(design_matrix_for_anova[[grouping_variable]])
        groups_with_single_sample <- sum(samples_per_group < 2)
        if (groups_with_single_sample > 0) {
          message(sprintf("*** NEG CTRL ANOVA WARNING: %d group(s) have only 1 sample after Pool exclusion ***", 
                         groups_with_single_sample))
        }
      } else {
        message("*** NEG CTRL ANOVA: Pool groups detected but no Pool samples found in data matrix ***")
      }
    } else {
      message("*** NEG CTRL ANOVA: No Pool/QC groups detected - using all samples for ANOVA ***")
    }
  }

  ## Inspired by matANOVA function from PhosR package: http://www.bioconductor.org/packages/release/bioc/html/PhosR.html

  grps <- design_matrix_for_anova[colnames(data_matrix_for_anova), grouping_variable]

  ps <- apply(data_matrix_for_anova, 1, function(x) {
       if( length( unique( grps[!is.na(x)] )  ) > 1 ) {
         summary(stats::aov(as.numeric(x) ~ grps))[[1]][["Pr(>F)"]][1]
       } else {
          return(NA_real_)
       }
    })

  ps[is.na(ps)] <- 1

  aov <- c()

  if ( ruv_fdr_method == "qvalue") {
    aov <- qvalue(unlist(ps))$qvalues
  } else if ( ruv_fdr_method == "BH") {
    aov <- qvalue(unlist(ps), pi0=1)$qvalues
  } else {
    stop("Input FDR method ", ruv_fdr_method, " is not valid")
  }


  filtered_list <- aov[aov > ruv_qval_cutoff]

  if (identical(candidate_rule, "p_id_two_groups")) {
    # KIT-190 rule (d) (VAL-110; lipidomics and metabolomics, VAL-126): features observed in fewer than two groups stay
    # in BH's family with p = 1 but are not candidates; candidates are ranked by p, highest first, ties broken by the
    # feature identifier in C-locale byte order, so the selection does not depend on the table's row order.
    observed_groups <- apply(data_matrix_for_anova, 1, function(x) length(unique(grps[!is.na(x)])))
    two_groups <- names(observed_groups)[observed_groups > 1]
    p_values <- unlist(ps)
    candidates <- intersect(names(filtered_list), two_groups)
    filtered_list <- filtered_list[candidates]
    ranked <- candidates[order(-p_values[candidates], candidates, method = "radix")]
    list_size <- ifelse(num_neg_ctrl > length(ranked), length(ranked), num_neg_ctrl)
    control_genes <- ranked[1:list_size]
  } else {

  list_size <- ifelse(num_neg_ctrl > length(filtered_list), length(filtered_list), num_neg_ctrl)

  control_genes <- names(sort(filtered_list, decreasing = TRUE)[1:list_size])
  }

  #nrow(data_matrix) - length(control_genes)
  control_genes_index <- rownames(data_matrix) %in% control_genes
  names(control_genes_index) <- rownames(data_matrix)


  return(control_genes_index)

}

