# ----------------------------------------------------------------------------
# findBestNegCtrlPercentage
# ----------------------------------------------------------------------------
#' Find the Best Negative Control Percentage for RUV-III Analysis
#'
#' This function automatically determines the optimal percentage of proteins to use
#' as negative controls for RUV-III analysis by testing different percentages and
#' evaluating the separation quality between "All" and "Control" groups in canonical
#' correlation plots.
#'
#' @param normalised_protein_matrix_obj A ProteinQuantitativeData object containing
#'   the normalized protein quantification data
#' @param percentage_range A numeric vector specifying the range of percentages to test.
#'   Default is seq(1, 20, by = 1) for testing 1% to 20% in 1% increments
#' @param num_components_to_impute Number of components to use for imputation in ruvCancor.
#'   Default is 5
#' @param ruv_grouping_variable The grouping variable to use for RUV analysis.
#'   Default is "group"
#' @param ruv_qval_cutoff The FDR threshold for negative control selection.
#'   Default is 0.05
#' @param ruv_fdr_method The FDR calculation method. Default is "qvalue"
#' @param separation_metric The metric to use for evaluating separation quality.
#'   Options: "max_difference" (default), "mean_difference", "auc", "weighted_difference"
#'   Note: "weighted_difference" is deprecated.
#' @param k_penalty_weight Weight for penalizing high k values in composite score.
#'   Default is 0.5. Higher values penalize high k more strongly
#' @param max_acceptable_k Maximum acceptable k value. k values above this get heavy penalty.
#'   Default is 3
#' @param adaptive_k_penalty Whether to automatically adjust max_acceptable_k based on sample size.
#'   Default is TRUE (recommended). Set to FALSE only if you need exact reproducibility with previous results
#' @param verbose Whether to print progress messages. Default is TRUE
#'
#' @return A list containing:
#'   \itemize{
#'     \item best_percentage: The optimal percentage as a numeric value
#'     \item best_k: The optimal k value (scalar integer) for the best percentage
#'     \item best_control_genes_index: The control genes index for the best percentage
#'     \item best_separation_score: The separation score for the best percentage
#'     \item best_composite_score: The composite score (separation penalized by k value)
#'     \item optimization_results: A data frame with one row per tested percentage
#'     \item best_cancor_plot: The canonical correlation plot for the best percentage
#'     \item separation_metric_used: The separation metric that was used
#'     \item k_penalty_weight: The k penalty weight that was used
#'     \item max_acceptable_k: The maximum acceptable k value that was used
#'   }
#'
#' @importFrom logger log_info log_warn
#' @importFrom purrr imap map_dfr
#' @export
findBestNegCtrlPercentage <- function(normalised_protein_matrix_obj,
                                      percentage_range = seq(1, 20, by = 1),
                                      num_components_to_impute = 5,
                                      ruv_grouping_variable = "group",
                                      ruv_qval_cutoff = 0.05,
                                      ruv_fdr_method = "qvalue",
                                      separation_metric = "max_difference",
                                      k_penalty_weight = 0.5,
                                      max_acceptable_k = 3,
                                      adaptive_k_penalty = TRUE,
                                      verbose = TRUE) {

  # Emit weighted_difference deprecation warning once per public call
  if (identical(separation_metric, "weighted_difference")) {
    warning(
      paste0(
        "'weighted_difference' is deprecated because it up-weights high-K values ",
        "while the composite score penalizes high K. ",
        "Use 'max_difference' or 'mean_difference' instead."
      ),
      call. = FALSE
    )
  }


  # Input validation
  if (!inherits(normalised_protein_matrix_obj, "ProteinQuantitativeData")) {
    stop("normalised_protein_matrix_obj must be a ProteinQuantitativeData object")
  }

  if (length(percentage_range) == 0 || any(percentage_range <= 0) || any(percentage_range > 100)) {
    stop("percentage_range must contain values between 0 and 100")
  }

  if (!separation_metric %in% c("max_difference", "mean_difference", "auc", "weighted_difference")) {
    stop("separation_metric must be one of: 'max_difference', 'mean_difference', 'auc', 'weighted_difference'")
  }

  if (k_penalty_weight < 0 || k_penalty_weight > 1) {
    stop("k_penalty_weight must be between 0 and 1")
  }

  if (max_acceptable_k < 1 || !is.numeric(max_acceptable_k)) {
    stop("max_acceptable_k must be a positive number >= 1")
  }

  if (adaptive_k_penalty && max_acceptable_k < 3) {
    stop("max_acceptable_k must be at least 3 when adaptive_k_penalty is TRUE")
  }

  # Pre-compute quantities constant across all percentages
  candidate_feature_count <- nrow(normalised_protein_matrix_obj@protein_quant_table)
  sample_size <- ncol(normalised_protein_matrix_obj@protein_quant_table) - 1L

  # Calculate adaptive max_acceptable_k if requested
  if (adaptive_k_penalty) {
    adaptive_max_k <- calculateAdaptiveMaxK(sample_size)

    if (verbose) {
      log_info("Adaptive penalty enabled: Sample size = {sample_size}, Adaptive max_acceptable_k = {adaptive_max_k} (original = {max_acceptable_k})")
    }

    max_acceptable_k <- adaptive_max_k
  }

  if (sample_size < 15 && max(percentage_range) < 30) {
    if (verbose) {
      log_warn("Small dataset detected (n={sample_size}). Consider testing higher percentages (up to 30-50%) for better negative control identification.")
      log_warn("Current range: {paste(range(percentage_range), collapse = '-')}%. May need wider range for optimal results.")
    }
  }

  if (verbose) {
    log_info("Starting optimization of negative control percentage with k value consideration...")
    log_info("Testing {length(percentage_range)} different percentages: {paste(range(percentage_range), collapse = '-')}%")
    log_info("K penalty weight: {k_penalty_weight}, Max acceptable k: {max_acceptable_k}")
    if (adaptive_k_penalty) {
      log_info("Using adaptive k penalty based on sample size")
    }
    log_info("Processing {length(percentage_range)} percentages using vectorized operations...")
  }

  # Helper: build a trace row for a failed or skipped percentage
  .make_failed_row <- function(current_percentage, status, error_reason = "",
                                realized_num_controls = NA_integer_,
                                realized_percentage = NA_real_,
                                separation_score = NA_real_,
                                best_k = NA_integer_,
                                composite_score = NA_real_,
                                control_genes_index = NULL,
                                cancor_plot = NULL) {
    list(
      percentage_requested  = current_percentage,
      candidate_feature_count = candidate_feature_count,
      realized_num_controls = realized_num_controls,
      realized_percentage   = realized_percentage,
      sample_size           = sample_size,
      best_k                = best_k,
      separation_score      = separation_score,
      composite_score       = composite_score,
      status                = status,
      error_reason          = error_reason,
      control_genes_index   = control_genes_index,
      cancor_plot           = cancor_plot
    )
  }

  # The canonical-correlation input (NIPALS imputation when values are missing) does not depend on the
  # percentage: it is prepared once for the sweep instead of once per percentage (KIT-005; at 300 samples
  # the imputation took about 15 min and was repeated for each of the 20 percentages).
  if (!ruv_grouping_variable %in% colnames(normalised_protein_matrix_obj@design_matrix)) {
    stop(paste0("The 'ruv_grouping_variable = ", ruv_grouping_variable, "' is not a column in the design matrix."))
  }
  if (is.na(num_components_to_impute) || num_components_to_impute < 1) {
    stop(paste0("The num_components_to_impute = ", num_components_to_impute, " value is invalid."))
  }
  cancor_input <- prepareRuvCancorInput(normalised_protein_matrix_obj, num_components_to_impute)
  # RUV-III can estimate at most as many factors as it has control proteins observed in every sample
  # (KIT-005, user decision 2026-10-10: at 300 samples the sweep chose 1 % controls with k = 15 while only
  # 3 of those 25 controls were complete, and the correction returned no finite values). A percentage whose
  # elbow k exceeds its complete controls is not viable and is skipped, not re-scored.
  complete_rows <- ruvCompleteControlRows(normalised_protein_matrix_obj)

  # Process a single percentage, returning a fully annotated trace record
  process_percentage <- function(current_percentage, index) {
    if (verbose && index %% 5 == 0) {
      log_info("Testing percentage {index}/{length(percentage_range)}: {current_percentage}%")
    }

    # Step 1: Select negative controls
    ctrl_error <- NULL
    control_genes_index <- tryCatch({
      getNegCtrlProtAnova(
        normalised_protein_matrix_obj,
        ruv_grouping_variable = ruv_grouping_variable,
        percentage_as_neg_ctrl = current_percentage,
        ruv_qval_cutoff = ruv_qval_cutoff,
        ruv_fdr_method = ruv_fdr_method
      )
    }, error = function(e) {
      ctrl_error <<- e$message
      NULL
    })

    if (is.null(control_genes_index)) {
      if (verbose) {
        log_warn(paste("Percentage", current_percentage, "% : Error in getNegCtrlProtAnova:", ctrl_error))
      }
      return(.make_failed_row(current_percentage, "error_neg_ctrl_selection",
        error_reason = if (is.null(ctrl_error)) "" else ctrl_error))
    }

    # Step 2: Check minimum control count
    realized_num_controls <- sum(control_genes_index, na.rm = TRUE)
    realized_percentage <- if (candidate_feature_count > 0L) {
      100 * realized_num_controls / candidate_feature_count
    } else {
      NA_real_
    }

    if (realized_num_controls < 5L) {
      if (verbose) {
        log_warn("Percentage {current_percentage}%: Only {realized_num_controls} control genes found (minimum 5 required). Skipping.")
      }
      return(.make_failed_row(current_percentage, "skipped_insufficient_controls",
        realized_num_controls = realized_num_controls,
        realized_percentage = realized_percentage))
    }

    # Step 3: Canonical correlation
    cancor_error <- NULL
    cancorplot <- tryCatch({
      ruvCancorFromInput(cancor_input, normalised_protein_matrix_obj, control_genes_index, ruv_grouping_variable)
    }, error = function(e) {
      cancor_error <<- e$message
      NULL
    })

    if (is.null(cancorplot)) {
      if (verbose) {
        log_warn(paste("Percentage", current_percentage, "% : Error in ruvCancor:", cancor_error))
      }
      return(.make_failed_row(current_percentage, "error_cancor",
        realized_num_controls = realized_num_controls,
        realized_percentage = realized_percentage,
        error_reason = if (is.null(cancor_error)) "" else cancor_error,
        control_genes_index = control_genes_index))
    }

    # Step 4: Score the result
    # KIT-123 R1: k is bounded. The score and the elbow read the curve up to `max_acceptable_k` (2 to 5 by sample
    # size when adaptive), as `findBestNegCtrlPercentageCapped` limits it for DIA_LIMPA; before, the limit entered
    # only the penalty that ranks percentages and the elbow could return any K (44 on a 297-sample corpus). The
    # plot that is kept and shown is the whole curve.
    bounded_curve <- cancorplot
    if (is.data.frame(bounded_curve$data) && "K" %in% names(bounded_curve$data)) {
      bounded_curve$data <- bounded_curve$data[bounded_curve$data$K <= max_acceptable_k, , drop = FALSE]
    }
    separation_score <- calculateSeparationScore(bounded_curve, separation_metric)

    best_k <- tryCatch(
      findBestKElbow(bounded_curve),
      error = function(e) NA_integer_
    )

    if (is.na(best_k)) {
      return(.make_failed_row(current_percentage, "invalid_cancor_plot",
        realized_num_controls = realized_num_controls,
        realized_percentage = realized_percentage,
        separation_score = separation_score,
        error_reason = "findBestKElbow returned NA",
        control_genes_index = control_genes_index,
        cancor_plot = cancorplot))
    }

    best_k <- as.integer(best_k)
    complete_controls <- sum(complete_rows[which(control_genes_index)], na.rm = TRUE)
    if (best_k > complete_controls) {
      if (verbose) {
        log_warn("Percentage {current_percentage}%: elbow k = {best_k} exceeds the {complete_controls} control proteins observed in every sample. Skipping.")
      }
      return(.make_failed_row(current_percentage, "skipped_k_exceeds_complete_controls",
        realized_num_controls = realized_num_controls,
        realized_percentage = realized_percentage,
        separation_score = separation_score,
        best_k = best_k,
        error_reason = sprintf("k = %d exceeds %d controls complete in every sample", best_k, complete_controls),
        control_genes_index = control_genes_index,
        cancor_plot = cancorplot))
    }
    composite_score <- calculateCompositeScore(
      separation_score,
      best_k,
      k_penalty_weight,
      max_acceptable_k
    )

    if (!is.finite(composite_score)) {
      return(.make_failed_row(current_percentage, "error_scoring",
        realized_num_controls = realized_num_controls,
        realized_percentage = realized_percentage,
        separation_score = separation_score,
        best_k = best_k,
        composite_score = composite_score,
        error_reason = "composite score is non-finite",
        control_genes_index = control_genes_index,
        cancor_plot = cancorplot))
    }

    list(
      percentage_requested  = current_percentage,
      candidate_feature_count = candidate_feature_count,
      realized_num_controls = realized_num_controls,
      realized_percentage   = realized_percentage,
      sample_size           = sample_size,
      best_k                = best_k,
      separation_score      = separation_score,
      composite_score       = composite_score,
      status                = "ok",
      error_reason          = "",
      control_genes_index   = control_genes_index,
      cancor_plot           = cancorplot
    )
  }

  all_results <- percentage_range |>
    purrr::imap(process_percentage)

  # Build optimization trace: one row per tested percentage, new schema primary,
  # deprecated aliases (percentage, num_controls, valid_plot) kept for one release cycle
  results <- all_results |>
    purrr::map_dfr(~ data.frame(
      percentage_requested    = .x$percentage_requested,
      candidate_feature_count = .x$candidate_feature_count,
      realized_num_controls   = .x$realized_num_controls,
      realized_percentage     = .x$realized_percentage,
      sample_size             = .x$sample_size,
      best_k                  = .x$best_k,
      separation_score        = .x$separation_score,
      composite_score         = .x$composite_score,
      status                  = .x$status,
      error_reason            = .x$error_reason,
      percentage              = .x$percentage_requested,
      num_controls            = .x$realized_num_controls,
      valid_plot              = identical(.x$status, "ok"),
      stringsAsFactors = FALSE
    ))

  # Deterministic winner selection — stable ordering replaces which.max()
  valid_df <- results |>
    dplyr::filter(is.finite(composite_score)) |>
    dplyr::arrange(
      dplyr::desc(composite_score),
      best_k,
      dplyr::desc(separation_score),
      percentage_requested
    )

  if (nrow(valid_df) == 0L) {
    complete_counts <- vapply(all_results, \(r) {
      if (!identical(r$status, "skipped_k_exceeds_complete_controls")) return(NA_integer_)
      sum(complete_rows[which(r$control_genes_index)], na.rm = TRUE)
    }, integer(1L))
    refusal <- ruvNoValidPercentageMessage(results$percentage_requested, results$status, results$best_k,
      complete_counts, "proteins")
    stop(if (is.null(refusal)) "No valid percentage found. Please check your data and parameters." else refusal)
  }

  best_percentage <- valid_df$percentage_requested[[1L]]

  # Retrieve the full record (with control_genes_index and cancor_plot) for the winner
  winner_idx <- which(
    vapply(all_results, function(r) r$percentage_requested == best_percentage, logical(1L))
  )[[1L]]
  best_result <- all_results[[winner_idx]]

  best_k                <- as.integer(best_result$best_k)
  best_control_genes_index <- best_result$control_genes_index
  best_cancor_plot      <- best_result$cancor_plot
  best_separation_score <- best_result$separation_score
  best_composite_score  <- best_result$composite_score

  if (verbose) {
    log_info("Optimization complete!")
    log_info("Best percentage: {best_percentage}% (composite score: {round(best_composite_score, 4)})")
    log_info("  - Separation score: {round(best_separation_score, 4)}")
    log_info("  - Best k value: {best_k}")
    log_info("  - Number of control genes: {sum(best_control_genes_index, na.rm = TRUE)}")
  }


  list(
    best_percentage          = best_percentage,
    best_k                   = best_k,
    best_control_genes_index = best_control_genes_index,
    best_separation_score    = best_separation_score,
    best_composite_score     = best_composite_score,
    optimization_results     = results,
    best_cancor_plot         = best_cancor_plot,
    separation_metric_used   = separation_metric,
    k_penalty_weight         = k_penalty_weight,
    max_acceptable_k         = max_acceptable_k,
    adaptive_k_penalty_used  = adaptive_k_penalty,
    sample_size              = sample_size
  )
}

# ----------------------------------------------------------------------------
# KIT-041: the limpa script's protein-level RUV optimiser and the RUV-III factors as covariates
# ----------------------------------------------------------------------------
#' The limpa script's negative-control percentage optimiser (`findBestNegCtrlPercentageCustom`, vendored at
#' `docs/qa/workflow-execution/kit/limpa-workflow/`), brought into the package with its behaviour kept exactly.
#' It differs from `findBestNegCtrlPercentage` in five ways: the canonical-correlation curve is capped at
#' `min(max_acceptable_k, n_controls - 1)` before scoring; `best_k` is the K at the maximum of the all-minus-control
#' canonical correlation on the capped curve (not `findBestKElbow`); the percentage range is 1-30 by default;
#' the FDR method is `BH` by default; and no percentage is skipped for exceeding its complete controls (the script
#' had no such rule). The winner is the first maximum of the composite score in percentage order (`which.max`).
#' @param normalised_protein_matrix_obj A `ProteinQuantitativeData` object (a complete log2 matrix on this route).
#' @param percentage_range,num_components_to_impute,ruv_grouping_variable,ruv_qval_cutoff,ruv_fdr_method,separation_metric,k_penalty_weight,max_acceptable_k,adaptive_k_penalty,verbose As the script.
#' @return `list(best_percentage, best_k, best_control_genes_index, best_separation_score, best_composite_score,
#'   optimization_results, best_cancor_plot, max_acceptable_k, sample_size)`; `optimization_results` has one row
#'   per tested percentage (`percentage`, `separation_score`, `best_k`, `composite_score`, `num_controls`,
#'   `valid_plot`, `error_reason`).
#' @export
findBestNegCtrlPercentageCapped <- function(normalised_protein_matrix_obj,
                                            percentage_range = seq(1, 30, by = 1),
                                            num_components_to_impute = 5,
                                            ruv_grouping_variable = "group",
                                            ruv_qval_cutoff = 0.05,
                                            ruv_fdr_method = "BH",
                                            separation_metric = "max_difference",
                                            k_penalty_weight = 0.5,
                                            max_acceptable_k = 3,
                                            adaptive_k_penalty = TRUE,
                                            verbose = TRUE) {
  if (!inherits(normalised_protein_matrix_obj, "ProteinQuantitativeData")) {
    stop("normalised_protein_matrix_obj must be a ProteinQuantitativeData object")
  }
  if (!ruv_grouping_variable %in% colnames(normalised_protein_matrix_obj@design_matrix)) {
    stop(paste0("The 'ruv_grouping_variable = ", ruv_grouping_variable, "' is not a column in the design matrix."))
  }
  sample_size <- ncol(normalised_protein_matrix_obj@protein_quant_table) - 1L
  if (adaptive_k_penalty) {
    max_acceptable_k <- calculateAdaptiveMaxK(sample_size)
  }
  # The canonical-correlation input does not depend on the control set (KIT-005): prepared once for the sweep;
  # `ruvCancor` on the same object computes the same matrix per percentage (the script's call).
  cancor_input <- prepareRuvCancorInput(normalised_protein_matrix_obj, num_components_to_impute)

  process_percentage <- function(current_percentage, index) {
    if (verbose && index %% 5 == 0) {
      log_info("Testing percentage {index}/{length(percentage_range)}: {current_percentage}%")
    }
    tryCatch({
      control_genes_index <- getNegCtrlProtAnova(
        normalised_protein_matrix_obj,
        ruv_grouping_variable = ruv_grouping_variable,
        percentage_as_neg_ctrl = current_percentage,
        ruv_qval_cutoff = ruv_qval_cutoff,
        ruv_fdr_method = ruv_fdr_method
      )
      num_controls <- sum(control_genes_index, na.rm = TRUE)
      if (num_controls < 5) {
        return(list(percentage = current_percentage, separation_score = NA_real_, best_k = NA_real_,
                    composite_score = NA_real_, num_controls = num_controls, valid_plot = FALSE,
                    error_reason = "fewer than 5 control proteins", control_genes_index = NULL, cancor_plot = NULL))
      }
      cancorplot <- ruvCancorFromInput(cancor_input, normalised_protein_matrix_obj, control_genes_index, ruv_grouping_variable)
      # Capping K to be strictly less than num_controls AND at most max_acceptable_k (the script's rule).
      limit_k <- min(max_acceptable_k, num_controls - 1)
      cancorplot$data <- cancorplot$data |> dplyr::filter(K <= limit_k)
      separation_score <- calculateSeparationScore(cancorplot, separation_metric)
      controls_idx <- which(cancorplot$data$featureset == "Control")
      all_idx <- which(cancorplot$data$featureset == "All")
      difference_between_all_ctrl <- cancorplot$data$cc[all_idx] - cancorplot$data$cc[controls_idx]
      max_difference <- max(difference_between_all_ctrl, na.rm = TRUE)
      best_idx <- which(difference_between_all_ctrl == max_difference)[1]
      best_k <- (cancorplot$data$K[controls_idx])[best_idx]
      composite_score <- calculateCompositeScore(separation_score, best_k, k_penalty_weight, max_acceptable_k)
      list(percentage = current_percentage, separation_score = separation_score, best_k = best_k,
           composite_score = composite_score, num_controls = num_controls, valid_plot = TRUE, error_reason = "",
           control_genes_index = control_genes_index, cancor_plot = cancorplot)
    }, error = function(e) {
      if (verbose) log_warn(paste0("Error at ", current_percentage, "%: ", e$message))
      list(percentage = current_percentage, separation_score = NA_real_, best_k = NA_real_,
           composite_score = NA_real_, num_controls = NA_integer_, valid_plot = FALSE,
           error_reason = e$message, control_genes_index = NULL, cancor_plot = NULL)
    })
  }

  all_results <- purrr::imap(percentage_range, process_percentage)
  results <- purrr::map_dfr(all_results, ~ data.frame(percentage = .x$percentage,
      separation_score = .x$separation_score, best_k = .x$best_k, composite_score = .x$composite_score,
      num_controls = .x$num_controls, valid_plot = .x$valid_plot, error_reason = .x$error_reason,
      stringsAsFactors = FALSE))
  valid_results <- all_results[!is.na(purrr::map_dbl(all_results, "composite_score"))]
  if (length(valid_results) == 0) {
    stop("No valid percentage found. Please check your data and parameters.")
  }
  best_index <- which.max(purrr::map_dbl(valid_results, "composite_score"))
  best_result <- valid_results[[best_index]]
  list(best_percentage = best_result$percentage, best_k = as.integer(best_result$best_k),
       best_control_genes_index = best_result$control_genes_index,
       best_separation_score = best_result$separation_score, best_composite_score = best_result$composite_score,
       optimization_results = results, best_cancor_plot = best_result$cancor_plot,
       max_acceptable_k = max_acceptable_k, sample_size = sample_size)
}

#' Restore each feature's level after an RUV-III correction (KIT-123 R2). RUV-III estimates W from the controls'
#' uncentred values, so the controls' mean level enters W and every feature is shifted by a constant. The shift is
#' removed: each feature's mean over the samples it was corrected in is set back to its mean before. Differences
#' between samples within a feature are not changed. On complete data this is the centred-W formula of the
#' RUV-III-PRPS implementation.
#' @param corrected,original Feature-by-sample matrices with the same dimension names.
#' @return `corrected`, each row shifted by a constant.
#' @noRd
restoreRuvFeatureLevels <- function(corrected, original) {
  stopifnot(is.matrix(corrected), is.matrix(original), identical(rownames(corrected), rownames(original)),
    identical(colnames(corrected), colnames(original)))
  both <- is.finite(corrected) & is.finite(original)
  shift <- rowSums(replace(original - corrected, !both, 0)) / rowSums(both)
  shift[!is.finite(shift)] <- 0
  corrected + shift
}

#' RUV-III factors as covariates (KIT-041, the limpa script's chunk 19b): `ruv::RUVIII` on the sample-by-protein
#' matrix with the replicate matrix of the design's replicate structure (KIT-035's rule: the declared technical
#' replicate block when the design has one, else the RUV grouping variable), the W factors
#' `Y[, ctl] %*% t(ac) %*% solve(ac %*% t(ac))` (`ac` the first `k` rows of `fullalpha` on the controls) named
#' `W1..Wk` (the controls centred on their means, KIT-123 R2), and the RUV-adjusted matrix (`Y - W alpha`) for QC
#' plots only. The quantified matrix is not changed.
#' @param theObject A `ProteinQuantitativeData` object (a complete matrix).
#' @param k Number of unwanted factors (a positive whole number).
#' @param controls Logical vector over the protein rows naming the negative controls.
#' @param ruv_grouping_variable Design column used when the design declares no technical replicates.
#' @return `list(W, adjusted, alpha, k, controls, replicate_structure, block_reason, blocks)`: `W` a sample-by-k
#'   matrix with the design's sample order, `adjusted` the protein-by-sample adjusted matrix.
#' @export
computeRuvCovariates <- function(theObject, k, controls, ruv_grouping_variable = "group") {
  if (!inherits(theObject, "ProteinQuantitativeData")) stop("theObject must be a ProteinQuantitativeData object")
  k <- validateProtNormRuvK(k, "k")
  design_matrix <- theObject@design_matrix
  sample_id <- theObject@sample_id
  sample_ids <- as.character(design_matrix[[sample_id]])
  matrix <- theObject@protein_quant_table |>
    column_to_rownames(theObject@protein_id_column) |>
    as.matrix()
  if (!all(sample_ids %in% colnames(matrix))) stop("the design names samples absent from the protein table")
  if (!is.logical(controls) || length(controls) != nrow(matrix)) stop("controls must be a logical vector over the protein rows")
  if (sum(controls, na.rm = TRUE) <= k) stop(sprintf("RUV-III needs more than %d control proteins for %d factors", k, k))
  Y <- t(matrix[, sample_ids, drop = FALSE])
  replicate_blocks <- resolveProtRuvReplicateBlocks(design_matrix, sample_id, theObject@group_id,
    theObject@technical_replicate_id, ruv_grouping_variable)
  block <- resolveProtTechnicalReplicateBlock(design_matrix, theObject@group_id, theObject@technical_replicate_id)
  M <- getRuvIIIReplicateMatrixHelper(replicate_blocks$design, !!sym(sample_id), .ruv_replicate_block)
  M <- M[sample_ids, , drop = FALSE]
  ruv_res <- ruv::RUVIII(Y = Y, M = M, ctl = controls, k = k, return.info = TRUE)
  alpha <- ruv_res$fullalpha[seq_len(k), , drop = FALSE]
  ac <- alpha[, controls, drop = FALSE]
  # KIT-123 R2: W from the controls centred on their means (the RUV-III-PRPS implementation's formula). From the
  # uncentred values, as `ruv::RUVIII` computes it, the controls' mean level (about 22 log2) enters W and the
  # adjusted matrix carries a constant shift per protein. `alpha` is the same either way.
  centred_controls <- sweep(Y[, controls, drop = FALSE], 2, colMeans(Y[, controls, drop = FALSE]))
  W <- centred_controls %*% t(ac) %*% solve(ac %*% t(ac))
  colnames(W) <- paste0("W", seq_len(k))
  rownames(W) <- sample_ids
  adjusted <- t(Y - W %*% alpha)
  list(W = W, adjusted = adjusted, alpha = alpha, k = k, controls = controls,
       replicate_structure = replicate_blocks$structure, block_reason = block$reason, blocks = replicate_blocks$blocks)
}

